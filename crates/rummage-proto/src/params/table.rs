/// 留出至少 2 个核心给系统和前台程序
fn index_threads_default() -> ParamValue {
    let n = std::thread::available_parallelism().map_or(1, |n| n.get()) as i64;
    ParamValue::Int((n - 2).clamp(1, 64))
}

